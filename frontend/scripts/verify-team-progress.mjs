import assert from 'node:assert/strict';
import { teamProgress, programProgress } from '../src/utils/teamProgress.js';
const result = (teamId, states) => ({ teamId, evaluations: states.map(status => ({ submission: status ? { status } : null })) });
assert.equal(teamProgress(result(1, [])).status, 'UNASSIGNED', 'zero reviewers is not completed');
assert.equal(teamProgress(result(1, [null, null])).status, 'PENDING');
assert.equal(teamProgress(result(1, ['DRAFT', null])).status, 'IN_PROGRESS', 'draft means work started');
assert.equal(teamProgress(result(1, ['DRAFT', null])).completed, 0, 'draft is not a completed review');
assert.equal(teamProgress(result(1, ['SUBMITTED', null])).status, 'IN_PROGRESS');
assert.equal(teamProgress(result(1, ['SUBMITTED', 'SUBMITTED'])).status, 'COMPLETE');
assert.equal(teamProgress(undefined).status, 'UNKNOWN', 'missing response cannot mean evaluation before start');
assert.equal(teamProgress(result(1, ['SUBMITTED']), false).status, 'UNKNOWN', 'failed refresh cannot masquerade as current results');
const summary = programProgress([{teamId:1}, {teamId:2}], [result(1, ['SUBMITTED', 'SUBMITTED']), result(2, ['DRAFT', null])]);
assert.equal(summary.completed, 2);
assert.equal(summary.assigned, 4);
assert.equal(summary.rate, 50, 'rate counts team-reviewer pairs, not completed reviewer accounts');
assert.deepEqual(summary.rows.map(team => team.number), [1, 2]);
assert.equal(summary.rows.filter(team => team.teamId === 2)[0].number, 2, 'filtering keeps original numbers');
assert.equal(programProgress([{teamId:1}], []).known, false);
assert.equal(programProgress([], []).rate, null, 'zero denominator is not a completion percentage');
assert.equal(programProgress([{teamId:1}], [result(1, [])]).rate, null);
assert.equal(programProgress([{teamId:2}], [result(1, ['SUBMITTED']), result(2, [null])]).completed, 0, 'exclude results for teams outside the displayed program roster');
console.log('PASS 17 team-progress state, stable-number, denominator and failure checks');
